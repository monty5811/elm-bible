#!/usr/bin/env python3
"""Generate src/tables.rs from the Elm package's source.

The Elm package in this repo (../src) is the reference implementation, so its
book table (Internal/Book.elm) and its alias tokens (Internal/Parser.elm) are
the single source of truth. This script reads them and writes the Rust
tables, so the two can't drift by hand.

    python3 rust/scripts/gen_tables.py           # rewrite src/tables.rs
    python3 rust/scripts/gen_tables.py --check   # exit 1 if it is stale

Pass --elm-src to read another copy of the package's src/, such as a published
version in Elm's package cache. The version in the generated header comes from
the elm.json next to that src/.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
ELM_SRC = CRATE.parent / "src"
PACKAGE = "monty5811/elm-bible"


def package_version(elm_src: Path) -> str:
    """The version in the elm.json beside `elm_src`."""
    return json.loads((elm_src.parent / "elm.json").read_text())["version"]


OUTPUT = CRATE / "src" / "tables.rs"

BOOK_DATA = re.compile(r'^\s+(\w+) ->\s*\n\s+BookData (\d+) "([^"]+)" (\d+) \[([\d,\s]*)\]', re.MULTILINE)
BOOKS_LIST = re.compile(r"^books =\n\s+\[(.*?)\]", re.MULTILINE | re.DOTALL)
TOKENS_LIST = re.compile(r"^bookTokens =\n\s+\[(.*?)\n\s+\]", re.MULTILINE | re.DOTALL)
TOKEN_ENTRY = re.compile(r"\(\s*(\w+),\s*\[([^\]]*)\]\s*\)")


def rust_variant(elm_constructor: str) -> str:
    # Samuel_1 -> Samuel1, Song_of_Solomon -> SongOfSolomon
    return "".join(part[:1].upper() + part[1:] for part in elm_constructor.split("_"))


def generate(elm_src: Path, version: str) -> str:
    book_elm = (elm_src / "Internal" / "Book.elm").read_text()
    parser_elm = (elm_src / "Internal" / "Parser.elm").read_text()

    data = {}
    for constructor, num, name, chapters, verses in BOOK_DATA.findall(book_elm):
        verse_counts = [int(v) for v in verses.replace(",", " ").split()]
        if len(verse_counts) != int(chapters):
            raise SystemExit(f"{constructor}: {chapters} chapters but {len(verse_counts)} verse counts")
        data[constructor] = (int(num), name, verse_counts)

    books_match = BOOKS_LIST.search(book_elm)
    if not books_match:
        raise SystemExit("could not find `books` in Book.elm")
    order = [b.strip() for b in books_match.group(1).replace("\n", " ").split(",")]
    if sorted(order) != sorted(data):
        raise SystemExit("`books` and `data` in Book.elm list different books")
    # Elm's Book.fromInt indexes `books`, Book.toInt reads BookData.num. They
    # must agree, or encode and decode disagree.
    for index, constructor in enumerate(order, start=1):
        if data[constructor][0] != index:
            raise SystemExit(f"{constructor}: BookData says {data[constructor][0]}, `books` position says {index}")

    tokens_match = TOKENS_LIST.search(parser_elm)
    if not tokens_match:
        raise SystemExit("could not find `bookTokens` in Parser.elm")
    tokens = []
    for constructor, token_list in TOKEN_ENTRY.findall(tokens_match.group(1)):
        if constructor not in data:
            raise SystemExit(f"bookTokens names unknown book {constructor}")
        for token in re.findall(r'"([^"]*)"', token_list):
            tokens.append((token, constructor))
    if {c for _, c in tokens} != set(data):
        raise SystemExit("bookTokens does not cover every book")
    # The Elm parser tries the aliases longest first (a stable sort, so ties
    # keep the table's order). Every alias is ASCII, so len() is Elm's
    # String.length.
    if not all(t.isascii() for t, _ in tokens):
        raise SystemExit("an alias is not ASCII")
    if "List.sortBy (\\( token, _ ) -> negate (String.length token))" not in parser_elm:
        raise SystemExit("Parser.elm no longer sorts the aliases longest first; update gen_tables.py")
    by_book = list(tokens)
    tokens = sorted(tokens, key=lambda t: -len(t[0]))

    out = [
        "// @generated by rust/scripts/gen_tables.py from the Elm package",
        f"// {PACKAGE} {version} (src/Internal/{{Book,Parser}}.elm). Do not edit by hand:",
        "// change the Elm source and rerun the script.",
        "",
        "/// A book of the 66-book Protestant canon, numbered 1 (Genesis) to 66 (Revelation).",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]",
        "#[repr(u8)]",
        '#[cfg_attr(feature = "python", pyo3::pyclass(eq, eq_int, ord, frozen, module = "elm_bible_rs"))]',
        "pub enum Book {",
    ]
    for constructor in order:
        out.append(f"    {rust_variant(constructor)} = {data[constructor][0]},")
    out += [
        "}",
        "",
        "pub(crate) struct BookData {",
        "    pub name: &'static str,",
        "    pub verses: &'static [u16],",
        "}",
        "",
    ]
    out.append("/// Indexed by `Book as usize - 1`.")
    out.append(f"pub(crate) static BOOKS: [BookData; {len(order)}] = [")
    for constructor in order:
        _num, name, verses = data[constructor]
        out.append(f'    BookData {{ name: "{name}", verses: &[{", ".join(map(str, verses))}] }},')
    out += ["];", ""]
    out.append(f"pub(crate) static ALL: [Book; {len(order)}] = [")
    for constructor in order:
        out.append(f"    Book::{rust_variant(constructor)},")
    out += ["];", ""]
    out.append("/// Alias tokens in the order the parser tries them: longest first. The first")
    out.append("/// one that starts the remaining input, with no letter straight after it, wins.")
    out.append(f"pub(crate) static TOKENS: [(&str, Book); {len(tokens)}] = [")
    for token, constructor in tokens:
        out.append(f'    ("{token}", Book::{rust_variant(constructor)}),')
    out += ["];", ""]
    out.append("/// The same aliases in the Elm table's order, which `Bible.Book.aliases` keeps.")
    out.append(f"pub(crate) static ALIASES: [(&str, Book); {len(by_book)}] = [")
    for token, constructor in by_book:
        out.append(f'    ("{token}", Book::{rust_variant(constructor)}),')
    out += ["];", ""]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--elm-src", type=Path, default=ELM_SRC, help="the package's src/ (default: ../src)")
    parser.add_argument("--check", action="store_true", help="fail if src/tables.rs is out of date")
    args = parser.parse_args()

    generated = generate(args.elm_src, package_version(args.elm_src))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            print(f"{OUTPUT} is out of date; run {Path(__file__).name}", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(generated)
    return 0


if __name__ == "__main__":
    sys.exit(main())
